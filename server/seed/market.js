const IMAGE_BY_TYPE = {
  apartment: 'apartment',
  townhouse: 'townhouse',
  villa: 'villa',
  house: 'villa',
  quinta: 'quinta',
  penthouse: 'terrace',
};

export function imageFor(property) {
  if (property.image) return property.image;
  const city = String(property.city || '').toLowerCase();
  if (['lisbon', 'cascais', 'estoril', 'oeiras', 'sintra'].includes(city)) return 'lisbon';
  return IMAGE_BY_TYPE[property.type] || 'apartment';
}

export const SOURCE_BY_ID = new Map(SOURCES.map((source) => [source.id, source]));

/** Flatten the base properties into one row per source copy. */
export function marketListings() {
  const rows = [];
  for (const property of MARKET) {
    for (const [sourceId, reference, priceOverride] of property.sources) {
      const source = SOURCE_BY_ID.get(sourceId);
      if (!source) continue;
      rows.push({
        id: `${property.id}__${sourceId}`,
        cluster: property.cluster,
        sourceId,
        sourceName: source.name,
        sourceKind: source.kind,
        reliability: source.reliability,
        reference,
        title: property.title,
        transaction: property.transaction,
        type: property.type,
        city: property.city,
        cityKey: cityKey(property.city),
        area: property.area,
        bedrooms: property.bedrooms,
        bathrooms: property.bathrooms,
        areaM2: property.areaM2,
        price: priceOverride ?? property.price,
        features: [...property.features],
        blurb: property.blurb,
        available: property.available ?? null,
        listedDaysAgo: property.listedDaysAgo ?? 14,
        image: imageFor(property),
        agent: property.agent ?? source.name,
      });
    }
  }
  return rows;
}

/** Canonical copy of every market cluster, used for price comparisons. */
export function canonicalMarket() {
  const byCluster = new Map();
  for (const listing of marketListings()) {
    const current = byCluster.get(listing.cluster);
    if (!current || listing.reliability > current.reliability) {
      byCluster.set(listing.cluster, listing);
    }
  }
  return [...byCluster.values()];
}

